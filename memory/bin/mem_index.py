#!/usr/bin/env python3
"""Regenerate vault indexes and grep maps from markdown frontmatter.

Why: Automated index generation prevents documentation rot and ensures lookup maps stay synchronized with note metadata.

Usage:
  python bin/mem_index.py
"""
import re
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mem_vault import VAULT

WIKI = VAULT / "wiki"
GEN = "<!-- GENERATED by bin/mem_index.py on {today}. Do not hand-edit: change page frontmatter instead. -->"
FM = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n", re.S)


def frontmatter(path: Path) -> dict:
    if not path.exists():
        return {"_body": ""}
    text = path.read_text(encoding="utf-8", errors="replace")
    m = FM.match(text)
    fm = {}
    if m:
        for line in m.group(1).splitlines():
            k, _, v = line.partition(":")
            if _ and not line.startswith((" ", "-")):
                fm[k.strip()] = v.strip().strip('"')
    fm["_body"] = text[m.end():] if m else text
    return fm


def first_heading(fm: dict, fallback: str) -> str:
    title = fm.get("title")
    if title:
        return title
    m = re.search(r"^#\s+(.+)$", fm.get("_body", ""), re.M)
    return m.group(1).strip() if m else fallback


def day(s: str) -> str:
    return (s or "")[:10]


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.read_text(encoding="utf-8", errors="replace") if path.exists() else ""
    nl = "\r\n" if "\r\n" in old else "\n"
    new = text.replace("\n", nl)
    if new != old:
        path.write_text(new, encoding="utf-8", newline="")


def rule_count(path: Path) -> int:
    if not path.exists():
        return 0
    return sum(1 for l in path.read_text(encoding="utf-8", errors="replace").splitlines() if l.startswith("- "))


def projects():
    rows = []
    projects_dir = WIKI / "projects"
    if projects_dir.exists():
        for p in sorted(projects_dir.glob("*.md")):
            if p.name.startswith("_"):
                continue
            fm = frontmatter(p)
            rows.append((day(fm.get("updated")), p.stem, first_heading(fm, p.stem), fm.get("status", "")))
    rows.sort(reverse=True)
    return rows


def sessions(limit=15):
    rows = []
    sessions_dir = WIKI / "sessions"
    if sessions_dir.exists():
        for p in sessions_dir.glob("20*.md"):
            fm = frontmatter(p)
            rows.append((p.stem[:10], p.stem, first_heading(fm, p.stem)))
    rows.sort(reverse=True)
    return rows[:limit], len(rows)


def rules_index() -> str:
    today = date.today().isoformat()
    lines = [
        "---",
        "type: index",
        'title: "Rules — grep map"',
        f"updated: {today}",
        "tags: [index, rules]",
        "status: evergreen",
        "---",
        GEN.format(today=today),
        "",
        "# Rules — grep map",
        "",
        "ON DEMAND ONLY. Grep one file by a hint word, read matching lines. Never read a whole file at boot.",
        "Boot rules (one line each) live in [[meta/lessons-learned]]; these files hold domain rules and detailed gotchas.",
        "",
        "| File | Rules | KB | Read when | Grep hints |",
        "|---|---|---|---|---|",
    ]
    rules_dir = WIKI / "meta/rules"
    if rules_dir.exists():
        for p in sorted(rules_dir.glob("*.md")):
            if p.name == "_index.md":
                continue
            fm = frontmatter(p)
            hints = fm.get("hints", p.name)
            read_when = fm.get("read_when", fm.get("description", fm.get("title", "")))
            lines.append(
                f"| `rules/{p.name}` | {rule_count(p)} | {p.stat().st_size // 1024} | "
                f"{read_when} | {hints} |"
            )
    lines += [
        "",
        "Archives (grep only, never boot): [[meta/lessons-archive]] (archived rules), "
        "[[hot-archive]] (older session headlines).",
    ]
    return "\n".join(lines) + "\n"


def projects_index(rows) -> str:
    today = date.today().isoformat()
    lines = [
        "---",
        "type: index",
        'title: "Projects Index"',
        f"updated: {today}",
        "tags: [index, projects]",
        "status: evergreen",
        "---",
        GEN.format(today=today),
        "",
        "# Projects Index",
        "",
        "Newest `updated:` first. Each hub holds the project's state; its repo instruction file holds the rules.",
        "",
        "| Updated | Hub | Title | Status |",
        "|---|---|---|---|",
    ]
    lines += [f"| {u or '?'} | [[projects/{slug}]] | {title} | {status} |" for u, slug, title, status in rows]
    archived_dir = WIKI / "projects/_archived"
    archived = sorted(p.stem for p in archived_dir.glob("*.md")) if archived_dir.exists() else []
    if archived:
        lines += ["", f"Archived ({len(archived)}): " + " · ".join(f"[[projects/_archived/{a}]]" for a in archived)]
    return "\n".join(lines) + "\n"


def main_index(proj_rows, sess_rows, sess_total) -> str:
    today = date.today().isoformat()
    counts = {}
    if WIKI.exists():
        counts = {
            d.name: len(list(d.glob("*.md")))
            for d in sorted(WIKI.iterdir())
            if d.is_dir() and d.name not in ("projects", "sessions", "meta")
        }
    lines = [
        "---",
        "type: meta",
        'title: "Wiki Index"',
        f"updated: {today}",
        "tags: [meta, index]",
        "status: evergreen",
        "---",
        GEN.format(today=today),
        "",
        "# Wiki Index",
        "",
        "## Boot (injected every session by `bin/mem-boot.py`)",
        "- [[hot]] — recent session headlines (4.5 KB cap)",
        "- [[meta/lessons-learned]] — always-on rules, one line each (10 KB cap)",
        "- [[meta/rules/_index]] — grep map for domain rule files (on demand)",
        "- Write-back: `update-mem` skill; protocol: `MEMORY-PROTOCOL.md`; budgets: `bin/mem-budget.py`",
        "",
        "## Projects (newest first) — full table: [[projects/_index]]",
    ]
    lines += [f"- [[projects/{slug}]] — {title} ({u or '?'})" for u, slug, title, _ in proj_rows[:8]]
    lines += ["", f"## Sessions — latest of {sess_total}; timeline: [[sessions/_index]]"]
    lines += [f"- [[{slug}]] — {title}" for _, slug, title in sess_rows[:10]]
    if counts:
        lines += ["", "## Other folders (counts)", ", ".join(f"`{k}` {v}" for k, v in counts.items())]
    return "\n".join(lines) + "\n"


def patch_sessions_index(sess_rows) -> None:
    path = WIKI / "sessions/_index.md"
    if not path.exists():
        today = date.today().isoformat()
        initial = (
            "---\n"
            "type: index\n"
            'title: "Sessions Index"\n'
            f"updated: {today}\n"
            "tags: [index, sessions]\n"
            "status: evergreen\n"
            "---\n\n"
            "# Sessions Index\n\n"
            "Historical record of work sessions.\n\n"
            "<!-- mem-index:latest -->\n"
            "<!-- /mem-index:latest -->\n"
        )
        write(path, initial)
    text = path.read_text(encoding="utf-8", errors="replace")
    start, end = "<!-- mem-index:latest -->", "<!-- /mem-index:latest -->"
    block = "\n".join([start, f"Latest {len(sess_rows)} (generated by bin/mem_index.py):"]
                      + [f"- [[{slug}]] — {title}" for _, slug, title in sess_rows] + [end])
    if start in text and end in text:
        new = re.sub(re.escape(start) + r".*?" + re.escape(end), lambda _: block, text, count=1, flags=re.S)
    else:
        anchor = "## Chronological (newest first)"
        nl = "\r\n" if "\r\n" in text else "\n"
        new = text.replace(anchor, anchor + nl + nl + block.replace("\n", nl) + nl, 1) if anchor in text \
            else text.rstrip() + nl + nl + block.replace("\n", nl) + nl
    if new != text:
        path.write_text(new, encoding="utf-8", newline="")


def build() -> None:
    proj = projects()
    sess, total = sessions()
    write(WIKI / "meta/rules/_index.md", rules_index())
    write(WIKI / "projects/_index.md", projects_index(proj))
    write(WIKI / "index.md", main_index(proj, sess, total))
    patch_sessions_index(sess)


if __name__ == "__main__":
    build()
    print("indexes regenerated")
    sys.exit(0)
